/**
 * Общий признак «идёт переход» — чтобы полоску загрузки можно было зажечь
 * из места нажатия, а не только по хуку роутера.
 *
 * Зачем. `page:start` срабатывает поздно: замер 31 августа (390px, CPU ×4)
 * показал, что после нажатия проходит 812 мс полной тишины, а потом полоска
 * появляется ОДНОВРЕМЕННО с новой страницей. Полоска, приходящая вместе с
 * содержимым, бесполезна — она должна опережать его.
 */
export function usePageLoading() {
  return useState<boolean>('page-loading', () => false)
}
