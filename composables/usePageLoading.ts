/**
 * Общий признак «идёт переход» — чтобы полоску загрузки можно было зажечь
 * из места нажатия, а не только по хуку роутера.
 *
 * Зачем. `page:start` срабатывает поздно: замер 31 августа (390px, CPU ×4)
 * показал, что после нажатия проходит 812 мс полной тишины, а потом полоска
 * появляется ОДНОВРЕМЕННО с новой страницей. Полоска, приходящая вместе с
 * содержимым, бесполезна — она должна опережать его.
 */
export function usePageLoading() {
  return useState<boolean>('page-loading', () => false)
}

/**
 * Идёт ли переход прямо сейчас — для заглушки поверх содержимого.
 *
 * Отличается от `usePageLoading` тем, КОГДА поднимается. Тот признак включает
 * нижняя навигация по нажатию и хук `page:start`; этот поднимает
 * `plugins/scrollPosition.client.ts` в `beforeEach`, то есть на ЛЮБОМ
 * переходе — по ссылке в тексте, по карточке товара, по кнопке. Снимается по
 * `page:finish`, когда новая страница готова.
 *
 * Зачем вообще заглушка. Замер 2 сентября (390px, CPU ×4, Slow 4G): от
 * нажатия до смены адреса проходит ~400 мс, и всё это время на экране прежняя
 * страница. Анимацией это не лечится — она может начаться только после того,
 * как роутер разрешил переход, и лишь добавляется сверху (проверено дважды:
 * 442 → 592 мс).
 */
export function useNavigating() {
  return useState<boolean>('nav-navigating', () => false)
}
