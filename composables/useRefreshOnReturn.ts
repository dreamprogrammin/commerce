/**
 * Обновление данных при возврате на удержанную страницу.
 *
 * Зачем. С `keepalive: true` страница не пересобирается: `onMounted`
 * отрабатывает ОДИН раз за сессию. Всё, что загружено в нём, дальше застывает —
 * покупатель уходит в каталог, возвращается и видит статус заказа и баланс
 * бонусов такими, какими они были при первом заходе.
 *
 * Что делает. Вызывает `load(isReturn)` при первом появлении (`isReturn:
 * false`) и потом при каждом возврате (`isReturn: true`).
 *
 * Пропускается только то срабатывание `onActivated`, которое приходит в том же
 * такте, что и монтирование. Проверено 31 августа отладкой: в этой версии
 * `onActivated` при первом монтировании НЕ вызывается вовсе — но полагаться на
 * это нельзя, а без защиты от двойной загрузки пришлось бы. С защитой по такту
 * работают оба случая.
 *
 * Первая моя версия глушила первое срабатывание безусловно — и съедала как раз
 * первый настоящий возврат. Со стороны это выглядело как «приём не работает».
 *
 * Признак нужен, потому что «загрузить» и «перечитать» — разные вызовы. У
 * profileStore.loadProfile() без `force` есть ранний выход: профиль уже
 * загружен, и повторный вызов не сделает ничего.
 *
 * Почему не заменить `onMounted` на `onActivated` целиком: `onActivated`
 * вызывается ТОЛЬКО внутри `KeepAlive`. Компонент на неудерживаемой странице
 * тогда не загрузил бы данные вовсе. Здесь работают оба случая.
 */
export function useRefreshOnReturn(load: (isReturn: boolean) => void | Promise<void>) {
  let justMounted = false

  onMounted(() => {
    justMounted = true
    void load(false)
    // Снимаем признак в следующем такте: активация, идущая в паре с
    // монтированием, успевает попасть в тот же такт, настоящий возврат — нет.
    void nextTick(() => {
      justMounted = false
    })
  })

  onActivated(() => {
    if (justMounted)
      return
    void load(true)
  })
}
