import { onMounted, onUnmounted } from 'vue'

/**
 * Показ нижней панели телефона (MobileBottomNav) не прокруткой.
 *
 * Панель прячется при прокрутке вниз, и по тем же порогам вместе с ней едут
 * липкие панели страниц: покупка на странице товара, «Оформить заказ» в
 * корзине и на оформлении. Каждая считает это сама, по своей копии порогов.
 *
 * Кроме прокрутки, панель показывает полёт товара в корзину (useCartFly): на
 * телефоне корзина живёт в ней, и товар летит вниз, а панель выезжает
 * навстречу. До 25.11.2026 спрятанная панель выпадала из выбора цели, и товар
 * улетал вверх, обычно в пустой правый верхний угол.
 *
 * Подписываться обязана каждая копия порогов, иначе на таком показе панели
 * разъедутся: навигация встанет поверх липкой панели. Слушают и удержанные в
 * памяти страницы (`keepalive` у NuxtPage) — так же, как они слушают прокрутку.
 */
const REVEAL_EVENT = 'uhti:bottom-nav-reveal'

/** Показать нижнюю панель — и всё, что едет вместе с ней. */
export function revealBottomNav() {
  window.dispatchEvent(new Event(REVEAL_EVENT))
}

/** Подписка для каждой копии порогов прокрутки нижней панели. */
export function useBottomNavReveal(onReveal: () => void) {
  onMounted(() => window.addEventListener(REVEAL_EVENT, onReveal))
  onUnmounted(() => window.removeEventListener(REVEAL_EVENT, onReveal))
}
