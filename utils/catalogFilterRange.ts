/**
 * Диапазонный фильтр каталога: задан пользователем или это просто границы?
 *
 * Нужно потому, что границы диапазона (цена, число деталей) приходят с
 * сервера асинхронно, уже ПОСЛЕ того как `useCatalogQuery` посеял кеш на
 * сервере. До ответа в фильтре стоит заглушка, после — реальные границы
 * категории. Если подставлять их в фильтр как есть, ключ запроса меняется
 * между посевом и отрисовкой: `useQuery` читает данные по новому ключу, не
 * находит и отдаёт скелетоны — при том, что товары уже лежат в payload.
 *
 * Так терялась вся сетка категории: пустыми приходили 4 обхода из 12 на
 * превью и 9 из 12 на локальной сборке. Пустой рендер попадал в SWR-кеш
 * маршрута и раздавался оттуда полчаса, в том числе поисковому роботу.
 *
 * Сравнение с самим диапазоном устойчиво в обоих состояниях, поэтому ключ
 * получается один и тот же до и после загрузки границ.
 */
export interface FilterRange {
  min: number
  max: number
}

/**
 * `true`, если значение совпадает с границами диапазона, то есть фильтра
 * фактически нет и передавать его в запрос не нужно.
 *
 * Отсутствие значения или неизвестные ещё границы тоже считаются «фильтра
 * нет»: пока границы не пришли, сузить диапазон пользователь не мог.
 */
export function isWholeRange(
  value: readonly [number, number] | null | undefined,
  range: FilterRange | null | undefined,
): boolean {
  if (!value || !range)
    return true

  return value[0] === range.min && value[1] === range.max
}
