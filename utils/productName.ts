/**
 * Название товара без пробелов по краям и без двойных пробелов внутри.
 *
 * 22 сентября 2026 у 8 активных товаров из 178 название начиналось с
 * пробела — « Кукла шарнирная DEFA Lucy 8493…». Он уезжал в заголовок фида
 * Merchant Center и в разметку Product. Админка теперь чистит название при
 * сохранении, фид — при выдаче.
 */
export function cleanProductName(name: string | null | undefined): string {
  return (name ?? '').replace(/\s+/g, ' ').trim()
}
