import type { DehydratedState } from '@tanstack/vue-query'

/**
 * Состояние TanStack Query для HTML страницы — без времени запроса.
 *
 * `dehydrate()` кладёт в каждый запрос `dataUpdatedAt` и `errorUpdatedAt` —
 * миллисекунды момента рендера. Состояние уезжает в HTML (plugins/vue-query.ts),
 * поэтому два рендера одной страницы не совпадали никогда. А Vercel списывает
 * запись ISR, только когда пересобранная страница отличается от прежней
 * (docs: «ISR usage and pricing»): 10 октября 2026 записей было 767 тыс. при
 * бесплатных 200 тыс., и каждая пересборка главной, раздела, бренда и серии
 * была платной, даже если в базе ничего не менялось.
 *
 * Почему это ничего не меняет в браузере. Время нужно TanStack, чтобы решить,
 * свежи ли данные (`staleTime` — 5 минут). Страница из кеша ISR старше пяти
 * минут почти всегда, так что данные и раньше приходили «устаревшими», а
 * перезапрос при монтировании выключен (`refetchOnMount: false`).
 *
 * Почему 1, а не 0. Ноль — время пустого запроса, и `hydrate()` кладёт данные
 * в уже созданный запрос, только если они НОВЕЕ (`0 < 0` — нет). С нулём на
 * разделе браузер заново запрашивал `get_category_aggregate_rating`, которого
 * на бою не было; с единицей запросов из браузера столько же, сколько на бою
 * со старым кодом: главная, раздел, карточка, бренд, серия — 2/0/3/5/5
 * (замер 10 октября 2026). Единица — «очень давно»: как у страницы,
 * пролежавшей в кеше.
 */
export function withoutUpdateTimes(state: DehydratedState): DehydratedState {
  return {
    ...state,
    queries: state.queries.map(query => ({
      ...query,
      state: { ...query.state, dataUpdatedAt: 1, errorUpdatedAt: 0 },
    })),
  }
}
