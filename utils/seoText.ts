/**
 * Подготовка текста для мета-тегов и Schema.org.
 *
 * Заведено после аудита 20 августа 2026, где нашлись две ошибки одного рода.
 *
 * ПЕРВАЯ. `/brand/hstar` отдавал в `<meta name="description">` две тысячи
 * знаков сырого HTML: описание бренда бралось из `seo_description`, а там
 * лежит вёрстка целиком — `<h2 data-icon="…">`, списки, абзацы. В выдаче по
 * такому описанию показывать нечего. Поле заполнено HTML только у одного
 * бренда из 32, поэтому дефект и дожил незамеченным.
 *
 * ВТОРАЯ. Описание товара в разметке `Product` резалось ровно по 500-му
 * знаку, посреди слова: «…доставим по вс». Google берёт это описание в
 * сниппет как есть.
 *
 * Третья нашлась 26 сентября 2026: заголовок описания приклеивался к абзацу
 * без точки — см. `leadExcerpt` в конце файла.
 *
 * Все функции здесь — про то, чтобы из текста для человека получить текст для
 * робота: без разметки и обрезанный по границе слова.
 */

/** Убирает теги и схлопывает пробелы. HTML-сущности не раскрывает. */
export function toPlainText(html: string | null | undefined): string {
  if (!html)
    return ''

  return html
    .replace(/<[^>]*>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

/**
 * Обрезает по границе слова, а не по счётчику символов.
 *
 * Если ближайший пробел оказался слишком далеко от края (меньше 70% лимита),
 * режем всё-таки по лимиту: одно длинное слово не должно съедать пол-описания.
 * Многоточие не добавляется — в мета-описаниях оно только тратит знаки.
 */
/**
 * Служебные слова, которые нельзя оставлять последними.
 *
 * Обрезка по границе слова — необходимое, но не достаточное условие: на бою
 * 15 сентября 2026 мета-описание `/brand/cada` заканчивалось словами
 * «…военная техника и роботы для». Слово целое, а фраза оборвана, и в выдаче
 * это читается как сломанный сниппет.
 *
 * Список намеренно короткий: только предлоги, союзы и две отрицательные
 * частицы, то есть слова, которыми предложение закончиться не может. Наречия
 * и вводные сюда не идут — «…и роботы уже» звучит странно, но это авторский
 * текст, а не наш обрыв.
 */
const DANGLING_WORDS = new Set([
  'в',
  'во',
  'на',
  'над',
  'под',
  'при',
  'про',
  'за',
  'из',
  'изо',
  'от',
  'ото',
  'до',
  'для',
  'к',
  'ко',
  'с',
  'со',
  'у',
  'о',
  'об',
  'обо',
  'по',
  'без',
  'через',
  'между',
  'перед',
  'около',
  'после',
  'вокруг',
  'кроме',
  'ради',
  'и',
  'а',
  'но',
  'или',
  'либо',
  'да',
  'же',
  'ли',
  'бы',
  'что',
  'чтобы',
  'как',
  'если',
  'когда',
  'чем',
  'то',
  'не',
  'ни',
])

/** Хвостовые знаки препинания после обрыва фразы читаются как опечатка. */
function trimTail(text: string): string {
  return text.replace(/[\s,;:—–-]+$/, '')
}

export function truncateAtWord(text: string, maxLength: number): string {
  if (text.length <= maxLength)
    return text

  const cut = text.slice(0, maxLength)
  const lastSpace = cut.lastIndexOf(' ')

  let result = trimTail(lastSpace > maxLength * 0.7 ? cut.slice(0, lastSpace) : cut)

  /*
   * Снимаем служебные слова с хвоста, пока они там есть: «…и для» — это два
   * слова подряд. Ограничение в три шага — страховка от текста, целиком
   * состоящего из предлогов; такого не бывает, но цикл без потолка в утилите,
   * которая работает на каждой странице, оставлять не хочется.
   */
  for (let step = 0; step < 3; step++) {
    const space = result.lastIndexOf(' ')
    if (space === -1)
      break
    if (!DANGLING_WORDS.has(result.slice(space + 1).toLowerCase()))
      break
    result = trimTail(result.slice(0, space))
  }

  return result
}

/** Готовая выжимка из HTML: без разметки и по границе слова. */
export function plainExcerpt(
  html: string | null | undefined,
  maxLength: number,
): string {
  return truncateAtWord(toPlainText(html), maxLength)
}

/**
 * Абзацы про магазин, а не про предмет: сроки доставки, самовывоз, наличие.
 * Признак тот же, что у генератора вопросов `generate_brand_questions`, но
 * проверяется только ПЕРВАЯ фраза абзаца: абзацы про магазин с неё и
 * начинаются («Заказывайте…», «Какие модели сейчас в наличии…»), а абзац о
 * бренде бывает закончен такой фразой — у Mermaze «…с доставкой по Алматы и
 * Казахстану», и проверка по всему абзацу выбрасывала его целиком.
 */
const SHOP_PARAGRAPH = /доставк|самовывоз|в наличии/i

function isShopParagraph(paragraph: string): boolean {
  const firstSentence = paragraph.match(/^[\s\S]*?[.!?…](?=\s|$)/)?.[0] ?? paragraph
  return SHOP_PARAGRAPH.test(firstSentence)
}

/**
 * Текст одного абзаца. Теги внутри `<p>` строчные (`<strong>`, `<a>`), и
 * браузер пробелов на их месте не ставит, — поэтому снимаются без пробела,
 * иначе выходит «производитель .». Пробелом становится только `<br>`.
 */
function paragraphText(html: string): string {
  return html
    .replace(/<br\s*\/?>/gi, ' ')
    .replace(/<[^>]*>/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}

/**
 * Первый абзац о самом предмете — для описаний в разметке и мета-тегах.
 *
 * Описание бренда — вёрстка: заголовок, абзац, список, снова заголовок.
 * `plainExcerpt` снимал её целиком, и заголовок приклеивался к абзацу без
 * точки: на бою 26 сентября 2026 `Brand.description` у 29 брендов из 30 с
 * описанием начиналось так — «…машины для настоящих гонщиков Moka Toys —
 * китайский производитель…».
 *
 * Здесь берётся первый `<p>`, который не про магазин, без разметки и по
 * границе слова. Абзацев нет (описание — простой текст) — весь текст, как
 * раньше. Все абзацы про магазин — пустая строка: пусть сработает запасной
 * текст вызывающего.
 */
export function leadExcerpt(
  html: string | null | undefined,
  maxLength: number,
): string {
  if (!html)
    return ''

  const paragraphs = [...html.matchAll(/<p\b[^>]*>([\s\S]*?)<\/p>/gi)]
    .map(match => paragraphText(match[1] ?? ''))
    .filter(Boolean)
  if (paragraphs.length === 0)
    return plainExcerpt(html, maxLength)

  const lead = paragraphs.find(paragraph => !isShopParagraph(paragraph))
  return lead ? truncateAtWord(lead, maxLength) : ''
}

/**
 * Весь текст статьи без заголовков — для `articleBody` разделов.
 *
 * Раньше теги снимались без пробела, и заголовок срастался со следующим
 * словом («…в Алматы</h2><p>Машинки» → «АлматыМашинки»), а конец резался
 * посреди слова. Здесь берутся абзацы и пункты списков по порядку, каждый
 * кончается знаком препинания (у пунктов его обычно нет — ставится точка),
 * заголовки пропускаются, обрезка по границе слова. Нет ни абзацев, ни
 * пунктов — весь текст, как `plainExcerpt`.
 */
export function bodyExcerpt(
  html: string | null | undefined,
  maxLength: number,
): string {
  if (!html)
    return ''

  const blocks = [...html.matchAll(/<(p|li)\b[^>]*>([\s\S]*?)<\/\1>/gi)]
    .map(match => paragraphText(match[2] ?? ''))
    .filter(Boolean)
    .map(text => /[.!?…:;]$/.test(text) ? text : `${text}.`)
  if (blocks.length === 0)
    return plainExcerpt(html, maxLength)

  return truncateAtWord(blocks.join(' '), maxLength)
}

/**
 * Отбрасывает недописанное последнее слово у текста, пришедшего уже
 * обрезанным. Товары в списки раздела и бренда приходят из запроса каталога
 * без вёрстки и с оборванным концом — «…может собрать собс» (29 сентября
 * 2026). Признак обрыва — нет знака препинания в конце; тогда последнее
 * слово снимается, а за ним и служебные слова (`truncateAtWord`).
 */
export function dropBrokenTail(text: string): string {
  const trimmed = text.trim()
  if (!trimmed.includes(' ') || /[.!?…»")]$/.test(trimmed))
    return trimmed
  return truncateAtWord(trimmed, trimmed.length - 1)
}
