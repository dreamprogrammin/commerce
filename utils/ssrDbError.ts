/**
 * Сбой базы при серверной сборке страницы — 503, а не «данных нет».
 *
 * Зачем (9 октября 2026). Страницы каталога, брендов и серий лежат в кеше
 * ISR на Vercel. Если в момент пересборки база не ответила, страница всё
 * равно собиралась — с пустой сеткой (`fetchProducts` глушил ошибку) или
 * с 404 (бренд «не нашёлся», потому что запрос упал), — и такой ответ ложился
 * в кеш на весь срок: пустой раздел или «нет такого бренда» показывались всем,
 * включая робота. Ответ 5xx Vercel в кеш не кладёт и продолжает отдавать
 * прежнюю копию страницы.
 *
 * В браузере ничего не меняется: там ошибку показывает сама страница.
 */

/** PostgREST: `.single()` не нашёл строку — это «нет», а не сбой. */
export function isRowNotFound(error: { code?: string } | null | undefined): boolean {
  return error?.code === 'PGRST116'
}

/** На сервере: была ошибка загрузки — бросить 503, чтобы ответ не попал в кеш. */
export function failSsrOnDbError(error: unknown, what: string): void {
  if (import.meta.server && error) {
    throw createError({
      statusCode: 503,
      statusMessage: `Не удалось загрузить ${what}`,
      fatal: true,
    })
  }
}
