import { describe, expect, it } from 'vitest'
import { bodyExcerpt, dropBrokenTail, leadExcerpt, plainExcerpt, truncateAtWord } from '@/utils/seoText'

/*
 * Почему этот файл появился. На бою 15 сентября 2026 мета-описание
 * `/brand/cada` заканчивалось так:
 *
 *   «…спорткары, внедорожники, военная техника и роботы для»
 *
 * Обрезка по границе слова сработала правильно, а фраза всё равно оборвалась:
 * последним словом остался предлог. В выдаче это выглядит как сломанный
 * сниппет, и Google такой текст часто переписывает сам.
 */
describe('truncateAtWord', () => {
  it('не трогает текст короче предела', () => {
    expect(truncateAtWord('Конструкторы CaDA', 160)).toBe('Конструкторы CaDA')
  })

  it('режет по границе слова', () => {
    expect(truncateAtWord('Радиоуправляемые конструкторы из пластика', 30)).toBe(
      'Радиоуправляемые конструкторы',
    )
  })

  it('не оставляет предлог последним словом', () => {
    // Ровно случай `/brand/cada`: срез приходится на «…роботы для де|тей».
    expect(truncateAtWord('Военная техника и роботы для детей от 6 лет', 32)).toBe(
      'Военная техника и роботы',
    )
  })

  it('снимает несколько служебных слов подряд', () => {
    expect(truncateAtWord('Наборы для сборки и для игры дома', 26)).toBe('Наборы для сборки')
  })

  it('оставляет знаменательное слово на месте', () => {
    expect(truncateAtWord('Куклы и аксессуары для девочек', 22)).toBe('Куклы и аксессуары')
  })

  it('режет по пределу, если ближайший пробел слишком далеко', () => {
    expect(truncateAtWord('Сверхдлинноеслововначале текста', 20)).toBe('Сверхдлинноеслововна')
  })

  it('убирает хвостовую пунктуацию', () => {
    expect(truncateAtWord('Конструкторы, машинки, куклы, пазлы', 29)).toBe(
      'Конструкторы, машинки',
    )
  })
})

describe('plainExcerpt', () => {
  it('снимает разметку и обрывает по слову', () => {
    const html = '<h2>Конструкторы CaDA</h2><p>Наборы из ABS-пластика для детей от 6 лет</p>'
    expect(plainExcerpt(html, 40)).toBe('Конструкторы CaDA Наборы из ABS-пластика')
  })

  it('пустой ввод даёт пустую строку', () => {
    expect(plainExcerpt(null, 40)).toBe('')
  })
})

/*
 * Описание бренда — вёрстка: заголовок, абзац, список, снова заголовок. На
 * бою 26 сентября 2026 `Brand.description` у 29 брендов из 30 с описанием
 * начиналось заголовком, приклеенным к абзацу без точки: «…машины для
 * настоящих гонщиков Moka Toys — китайский производитель…». А у `/brand/hstar`,
 * где вёрстка лежит в `seo_description`, так же склеивалось мета-описание.
 */
describe('leadExcerpt', () => {
  const mokaToys = '<h2 data-icon="fluent-emoji-flat:racing-car">Moka Toys — радиоуправляемые машины для настоящих гонщиков</h2>\n'
    + '<p>Moka Toys — китайский производитель радиоуправляемых игрушек. В ассортименте — дрифт-кары и внедорожники.</p>\n'
    + '<h2>Купить Moka Toys в Казахстане — магазин Ухтышка</h2>\n'
    + '<p>Доставка по Алматы — 1–3 рабочих дня.</p>'

  it('берёт первый абзац, а не заголовок', () => {
    expect(leadExcerpt(mokaToys, 300)).toBe(
      'Moka Toys — китайский производитель радиоуправляемых игрушек. В ассортименте — дрифт-кары и внедорожники.',
    )
  })

  it('не приклеивает заголовок к абзацу', () => {
    expect(leadExcerpt(mokaToys, 300)).not.toContain('гонщиков Moka Toys')
  })

  it('пропускает абзацы про доставку, самовывоз и наличие', () => {
    const html = '<p>Какие модели сейчас в наличии, видно в каталоге.</p><p>Доставка по Алматы — 1–3 дня.</p><p>CaDA — конструкторы с моторами.</p>'
    expect(leadExcerpt(html, 300)).toBe('CaDA — конструкторы с моторами.')
  })

  it('абзац о бренде с фразой про доставку в конце не пропускает', () => {
    // Ровно случай Mermaze: о бренде, а последняя фраза — про доставку.
    const html = '<h2>Mermaze Mermaidz — русалки</h2><p>Mermaze Mermaidz — бренд кукол-русалок от MGA Entertainment. В Ухтышке — куклы с доставкой по Алматы.</p>'
    expect(leadExcerpt(html, 300)).toBe(
      'Mermaze Mermaidz — бренд кукол-русалок от MGA Entertainment. В Ухтышке — куклы с доставкой по Алматы.',
    )
  })

  it('снимает разметку внутри абзаца', () => {
    expect(leadExcerpt('<p><strong>LEGO</strong> — датский <a href="/x">производитель</a>.</p>', 300)).toBe(
      'LEGO — датский производитель.',
    )
  })

  it('режет по границе слова', () => {
    expect(leadExcerpt(mokaToys, 60)).toBe('Moka Toys — китайский производитель радиоуправляемых')
  })

  it('без абзацев — весь текст, как plainExcerpt', () => {
    const plain = 'Машины Hstar в Ухтышке — RC-дрифт в масштабах 1:24 и 1:43.'
    expect(leadExcerpt(plain, 40)).toBe(plainExcerpt(plain, 40))
  })

  it('только абзацы про магазин — пусто, чтобы сработал запасной текст', () => {
    expect(leadExcerpt('<h2>Купить</h2><p>Самовывоз из мкр. Шапагат.</p>', 300)).toBe('')
  })

  it('пустой ввод даёт пустую строку', () => {
    expect(leadExcerpt(null, 300)).toBe('')
  })
})

/*
 * `articleBody` разделов: весь текст статьи, но без заголовков. Раньше теги
 * снимались без пробела — «…в Алматы</h2><p>Машинки…» давало «АлматыМашинки»,
 * — а конец резался `substring` посреди слова.
 */
describe('bodyExcerpt', () => {
  const article = '<h2>Машинки в Алматы</h2><p>Машинки для детей.</p><h3>Как выбрать</h3><ul><li>По возрасту</li><li>По масштабу</li></ul><p>Доставка по Алматы — 1–3 дня.</p>'

  it('собирает абзацы и пункты без заголовков', () => {
    expect(bodyExcerpt(article, 500)).toBe('Машинки для детей. По возрасту. По масштабу. Доставка по Алматы — 1–3 дня.')
  })

  it('не склеивает слова на месте тегов', () => {
    expect(bodyExcerpt(article, 500)).not.toMatch(/АлматыМашинки|детей\.По/)
  })

  it('режет по границе слова', () => {
    expect(bodyExcerpt(article, 29)).toBe('Машинки для детей.')
  })

  it('без абзацев и списков — как plainExcerpt', () => {
    expect(bodyExcerpt('Простой текст раздела', 100)).toBe('Простой текст раздела')
  })

  it('пустой ввод даёт пустую строку', () => {
    expect(bodyExcerpt(null, 100)).toBe('')
  })
})

/*
 * Товары в списки раздела и бренда приходят из запроса каталога уже
 * обрезанными: «…из которых ребёнок может собрать собс». Страница не знает,
 * где оборвалось, — но фраза без знака препинания в конце и есть обрыв.
 */
describe('dropBrokenTail', () => {
  it('отбрасывает недописанное слово', () => {
    expect(dropBrokenTail('Ребёнок может собрать собс')).toBe('Ребёнок может собрать')
  })

  it('не трогает законченную фразу', () => {
    expect(dropBrokenTail('Набор для сборки трассы.')).toBe('Набор для сборки трассы.')
  })

  it('снимает и предлог, оставшийся в хвосте', () => {
    expect(dropBrokenTail('Трасса с петлёй для детал')).toBe('Трасса с петлёй')
    expect(dropBrokenTail('417 деталей для создания детал')).toBe('417 деталей для создания')
  })

  it('одно слово оставляет как есть', () => {
    expect(dropBrokenTail('Конструктор')).toBe('Конструктор')
  })
})
