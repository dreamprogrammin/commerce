/** Текст бренда, если он заведён статикой. Иначе — `null`, и покажется админский. */
export function brandStaticText(slug: string | null | undefined): string | null {
  if (!slug)
    return null
  return BRAND_STATIC_CONTENT[slug]?.html ?? null
}

/** Вопросы бренда: и на страницу, и в разметку `FAQPage`. */
export function brandStaticFaq(slug: string | null | undefined): BrandFaqItem[] {
  if (!slug)
    return []
  return BRAND_STATIC_CONTENT[slug]?.faq ?? []
}
