/** HTML-описание в ДАННЫЕ — текстом: нейросети хватит смысла, разметку она соберёт заново. */
function plain(value: string): string {
  return value.replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim()
}

/**
 * Полный текст для буфера обмена: правила + ДАННЫЕ (известное подставлено,
 * остальное — пустые строки для контент-менеджера) + задание.
 */
export function buildAdminPrompt(
  kind: AdminPromptKind,
  data: Record<string, string | number | null | undefined> = {},
): string {
  const lines = DATA_LINES[kind].map(([label, key]) => {
    const raw = key ? data[key] : undefined
    const value = raw === null || raw === undefined ? '' : plain(String(raw))
    return `- ${label}: ${value}`
  })
  return `${PROMPT_COMMON_RULES}\n\n${TASKS[kind].replace('ПОЛЯ:', `ДАННЫЕ:\n${lines.join('\n')}\n\nПОЛЯ:`)}\n`
}
