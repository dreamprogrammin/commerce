--
--  ЧТО СЛУЧИЛОСЬ. У 9 активных товаров из 178 в названии лишние пробелы: у 8
--  оно начинается с пробела («⎵Кукла шарнирная DEFA Lucy 8493…»), у одного
--  двойной пробел внутри. Пробел уезжает в заголовок фида Merchant Center, в
--  разметку Product на страницах и в фид Kaspi.
--
--  Код с 22 сентября чистит название и сам: фид — при выдаче
--  (utils/merchantFeed.ts), админка — при сохранении
--  (adminProductsStore, utils/productName.ts). Этот скрипт убирает уже
--  лежащие в базе.
--
--  ЧТО ДЕЛАЕТ. Меняет только поле name: пробелы по краям срезаются, подряд
--  идущие внутри — в один. Адрес товара (slug) НЕ меняется: история адресов
--  (trg_product_slug_history) срабатывает только на slug, а других триггеров
--  на name нет. Меняется updated_at — у этих 9 товаров обновится lastmod в
--  карте сайта, это безвредно.
--
--  ПРОВЕРЕНО ЗАПУСКОМ на локальной базе: 178 боевых названий во временной
--  таблице, выражение меняет ровно 9 и совпадает с правилом кода у всех 178.
--  ИДЕМПОТЕНТНО: повторный запуск меняет ноль строк.

-- ── 0. ПОСМОТРЕТЬ ─────────────────────────────────────────────────────────
--  Ожидаемо: 9.

SELECT count(*) AS s_lishnimi_probelami
  FROM public.products
 WHERE name IS DISTINCT FROM btrim(regexp_replace(name, '\s+', ' ', 'g'));

-- ── 1. ПОЧИСТИТЬ ──────────────────────────────────────────────────────────
--  Ожидаемо: UPDATE 9.

BEGIN;

UPDATE public.products
   SET name = btrim(regexp_replace(name, '\s+', ' ', 'g'))
 WHERE name IS DISTINCT FROM btrim(regexp_replace(name, '\s+', ' ', 'g'));

COMMIT;

