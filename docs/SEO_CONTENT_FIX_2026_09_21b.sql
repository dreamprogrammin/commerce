--
--  • 178 — ОШИБКА В САМОЙ ПРОВЕРКЕ, не в данных. Условие «пустой заголовок»
--    было написано как  <h2[^>]*>[^<]*</h2>  — а [^<]* допускает любой текст,
--    так что засчитывался каждый заголовок. Пустых <h2></h2> на бою ноль.
--    Файл от 21-го свою работу сделал: под его шаблон не подходит ни одна
--    карточка, сегодня обновлено ровно 66.
--
--  • 83 ВИСЯЩИХ ЗАГОЛОВКА «Купить … в Казахстане — Ухтышка»: сразу за ними
--    начинается следующий заголовок, под ними пусто. У всех 83 последняя
--    правка — 17 сентября: это раздел 2 файла SEO_CONTENT_FIX_2026_09_16.sql.
--    Он убрал абзац «Доставляем по всему Казахстану…», а заголовок над ним
--    оставил. Ошибка того файла, видна на 83 страницах товаров с 17-го.
--
--  • 29 ПАР «заголовок + абзац» другой формулировки: файл от 21-го искал
--    «доставляем / доставим», а здесь «С ДОСТАВКОЙ по всему Казахстану» (28)
--    и «с быстрой доставкой» (1, заголовок без «— Ухтышка»).
--
--  ПРОВЕРЕНО ЗАПУСКОМ: все 178 описаний с боя положены во временную таблицу
--  локальной базы, оба UPDATE применены, ROLLBACK. Задето 29 и 83 строки,
--  после правки все пять проверок ниже — нули, пустых описаний нет, абзац с
--  фактами о товаре сразу переходит в «Почему выбирают…».
--
--  ИДЕМПОТЕНТНО: второй прогон задевает ноль строк.

-- ── 0. СНАЧАЛА ПОСЧИТАТЬ ───────────────────────────────────────────────────
--  Ожидаемо на 21 сентября: para = 29, visyashchih = 83.

SELECT count(*) FILTER (WHERE description ~ '<h2[^>]*>[^<]*Купить[^<]*</h2>\s*<p>[^<]*доставк[^<]*по всему Казахстану[^<]*</p>') AS para,
       count(*) FILTER (WHERE description ~ '<h2[^>]*>[^<]*в Казахстане — Ухтышка</h2>\s*<h[1-6]')                           AS visyashchih
  FROM public.products;


-- ── 1. ПРАВКА ──────────────────────────────────────────────────────────────
--  Порядок важен: сначала пары (их заголовок уходит вместе с абзацем), потом
--  висящие заголовки. Ожидаемо: UPDATE 29, затем UPDATE 83.

BEGIN;

-- 1а. Пары «Купить …» + абзац про доставку любой формулировки.
UPDATE public.products
   SET description = trim(regexp_replace(description,
         '<h2[^>]*>[^<]*Купить[^<]*</h2>\s*<p>[^<]*доставк[^<]*по всему Казахстану[^<]*</p>\s*', '', 'g'))
 WHERE description ~ '<h2[^>]*>[^<]*Купить[^<]*</h2>\s*<p>[^<]*доставк[^<]*по всему Казахстану[^<]*</p>';

-- 1б. Висящие заголовки: сразу за ними другой заголовок. Сам следующий
--     заголовок сохраняется — он захвачен в группу и возвращается на место.
UPDATE public.products
   SET description = regexp_replace(description,
         '<h2[^>]*>[^<]*в Казахстане — Ухтышка</h2>\s*(<h[1-6])', '\1', 'g')
 WHERE description ~ '<h2[^>]*>[^<]*в Казахстане — Ухтышка</h2>\s*<h[1-6]';

--  Сверить «UPDATE 29» и «UPDATE 83» с разделом 0. Не сошлось — ROLLBACK.
COMMIT;


-- ── 2. ПРОВЕРИТЬ ───────────────────────────────────────────────────────────
--  Ожидаемо: все пять чисел — ноль.
--  pustyh_zagolovkov здесь считает ПО-НАСТОЯЩЕМУ пустые <h2></h2> — в файле
--  от 21-го это условие было написано так, что ловило любой заголовок.

SELECT count(*) FILTER (WHERE description LIKE '%по всему Казахстану%')                    AS ostalos_abzacev,
       count(*) FILTER (WHERE description LIKE '%в Казахстане — Ухтышка%')                 AS ostalos_zagolovkov,
       count(*) FILTER (WHERE description ~ '<h2[^>]*>\s*</h2>')                           AS pustyh_zagolovkov,
       count(*) FILTER (WHERE description ~ '<h2[^>]*>[^<]*Купить[^<]*</h2>\s*(<h[1-6]|$)') AS visyashchih_kupit,
       count(*) FILTER (WHERE description IS NULL OR btrim(description) = '')               AS pustyh_opisaniy
  FROM public.products;
