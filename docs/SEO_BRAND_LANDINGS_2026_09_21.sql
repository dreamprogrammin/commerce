--
--  ЧТО СЛУЧИЛОСЬ. В category_brand_seo 14 строк. Восемь написаны руками
--  целиком (длинные тексты про SOBA, Sluban, MG Toys, Play Smart, L.O.L. и
--  др.) — их этот скрипт НЕ трогает. Пять собраны кнопкой «Автогенерация» в
--  админке, и сохранённое страница берёт первым, поэтому на бою висит:
--
--      H1 и title   «Конструкторы Мальчикам LEGO — купить в Алматы»
--                   «Конструкторы малышам Smoneo — купить в Алматы»
--                   «Куклы L.O.L L.O.L. Surprise — купить в Алматы»
--      текст        «широкий выбор конструкторы малышам Smoneo — 8 моделей»,
--                   «3 моделей», «официальный интернет-магазин»,
--                   «часто выгоднее, чем на Kaspi»
--
--  Ещё у CaDA × «Конструкторы для мальчиков» заголовки написаны руками, а
--  текст шаблонный: «…купить оригинальные конструкторы мальчикам CaDA».
--
--  ЧТО ДЕЛАЕТ. У пяти шаблонных строк обнуляет H1, title, описание и текст,
--  у CaDA — только текст. С пустыми полями страница связки собирает всё сама
--  из своих товаров (utils/brandLandingText.ts): «Конструкторы LEGO для
--  мальчиков в Алматы», под заголовком «14 моделей · от 6 190 до 79 890 ₸»,
--  в описании для выдачи то же число и цены «от … до …», внизу — текст со
--  списком моделей и цен. Числа и цены берутся на каждом рендере, поэтому не
--  устаревают. Захотите свой текст для такой связки — строка остаётся в
--  /admin/brand-seo, её можно открыть и написать.
--
--  ПОРЯДОК НЕ ВАЖЕН — именно поэтому строки обнуляются, а не удаляются. Код,
--  который сейчас на uhti.kz, открывает связку для индекса, только если у неё
--  ЕСТЬ строка в category_brand_seo, и без строки ставит canonical на раздел.
--  Удали строки при нём — и четыре открытые связки (LEGO, Smoneo, Mermaze,
--  Defa Lucy) закрылись бы noindex. Пустая строка держит их открытыми при
--  любом коде; при старом заголовки останутся как сейчас, при новом соберутся
--  из товаров.
--
--  Шаблонное узнаётся по почерку генератора: H1 кончается на «— купить в
--  Алматы», title — на «— купить в Алматы с доставкой | Ухтышка», текст
--  начинается одной из четырёх заготовок. Скрипт сверяет число строк и при
--  расхождении откатывается целиком, ничего не изменив.
--
--  ФРАЗЫ ВОПРОСОВ (category_brand_questions) не трогаются: на сайте они не
--  показываются с 15 сентября 2026.
--
--  ПРОВЕРЕНО ЗАПУСКОМ на локальной базе: 14 строк скопированы с боя в
--  транзакции, скрипт отработал, ROLLBACK; написанные руками строки совпали
--  побайтно. Повторный запуск откатится с сообщением «нашлось 0» — это
--  значит, скрипт уже выполнен.

BEGIN;

DO $$
DECLARE
  n integer;
BEGIN
  UPDATE public.category_brand_seo
     SET seo_h1 = NULL, seo_title = NULL, seo_description = NULL, seo_text = NULL
   WHERE seo_h1 LIKE '% — купить в Алматы'
     AND seo_title LIKE '% — купить в Алматы с доставкой | Ухтышка'
     AND (
       seo_text IS NULL
       OR seo_text LIKE 'Ухтышка — это официальный интернет-магазин в %'
       OR seo_text LIKE 'В Ухтышке представлен широкий выбор %'
       OR seo_text LIKE 'Ищете % Ухтышка — уютный локальный магазин%'
       OR seo_text LIKE 'Ухтышка предлагает оригинальные %'
     );
  GET DIAGNOSTICS n = ROW_COUNT;
  IF n <> 5 THEN
    RAISE EXCEPTION 'ожидалось 5 шаблонных строк, нашлось % (если 0 — скрипт уже выполнен). Ничего не изменено.', n;
  END IF;

  UPDATE public.category_brand_seo
     SET seo_text = NULL
   WHERE seo_text LIKE 'Ухтышка — это официальный интернет-магазин в %'
     AND length(seo_text) < 600;
  GET DIAGNOSTICS n = ROW_COUNT;
  IF n <> 1 THEN
    RAISE EXCEPTION 'ожидался 1 шаблонный текст (CaDA), нашлось %. Ничего не изменено.', n;
  END IF;
END $$;

COMMIT;

-- ── ПРОВЕРИТЬ ──────────────────────────────────────────────────────────────
--  Ожидаемо: 14 | 5 | 0 | 0 | 0

SELECT count(*) AS vsego_strok,
       count(*) FILTER (WHERE seo_h1 IS NULL AND seo_title IS NULL AND seo_description IS NULL AND seo_text IS NULL) AS pustyh,
       count(*) FILTER (WHERE seo_h1 LIKE '% — купить в Алматы') AS shablonnyh_h1,
       count(*) FILTER (WHERE seo_text LIKE 'Ухтышка — это официальный интернет-магазин в %'
                           OR seo_text LIKE 'В Ухтышке представлен широкий выбор %'
                           OR seo_text LIKE 'Ищете % Ухтышка — уютный локальный магазин%'
                           OR seo_text LIKE 'Ухтышка предлагает оригинальные %') AS shablonnyh_tekstov,
       count(*) FILTER (WHERE seo_h1 ~ '(Мальчикам|Девочкам|малышам)') AS datelnyh_h1
  FROM public.category_brand_seo;
