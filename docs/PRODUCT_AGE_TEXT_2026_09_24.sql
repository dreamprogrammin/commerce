--
--  ЗАЧЕМ. Сверил возраст во всех 178 карточках: названия и описания против
--  характеристики «Возраст» (по ней работают фильтр, разметка и фид). У 14
--  расходится. Где на фото есть коробка с возрастом — верна коробка; где
--  коробки нет, но название и описание говорят одно и то же — характеристика
--  следует за ними. Так исправляется восемь карточек; шесть, где источники
--  спорят и коробки нет, в этот файл НЕ входят — их проверяет владелец по
--  живой коробке (список в docs/HANDOFF.md).
--
--  ЧТО ДЕЛАЕТ: шесть карточек — возраст в характеристике, «Ресторан» Smoneo
--  — возраст в названии («от 1.5 лет» при коробке «3+»), автотрек-пазл
--  1102AD — два места в описании («от года» при коробке «3+»).
--
--  Автоответы «С какого возраста…» подтянет триггер. Пишет, только если
--  значения такие же, как 24 сентября. Повторный запуск ничего не меняет.
--  ПРОВЕРЕНО ЗАПУСКОМ на локальной базе с копией боевых значений, с откатом.

-- ── 1. ПОМЕНЯТЬ ───────────────────────────────────────────────────────────
--  Ожидаемо: UPDATE 1 восемь раз.

BEGIN;

-- Smoneo 55015: коробка «3+», в названии и описании «от 3 лет»
UPDATE public.products SET min_age_months = 36
 WHERE id = 'acc9cc75-53bf-4b86-a0cd-b515dccc4e93' AND min_age_months = 24;

-- Smoneo 55013 «Школа»: в названии и описании «от 3 лет»; у коробок серии Live Zone «3+»
UPDATE public.products SET min_age_months = 36
 WHERE id = 'dfede753-18e1-4e68-884b-b5766683f76c' AND min_age_months = 24;

-- кукла DEFA Lucy Beauty 8502: коробка «3+» и «не для детей до 3 лет», в названии и описании «от 3 лет»
UPDATE public.products SET min_age_months = 36
 WHERE id = '80e16267-bd63-486b-a852-67ce7b694e60' AND min_age_months = 12;

-- говорящая книга 3103: коробка «3+», в названии и описании «от 3 лет»
UPDATE public.products SET min_age_months = 36
 WHERE id = '56be98a6-d59d-4e02-9db6-0141831ce95a' AND min_age_months = 24;

-- посуда Little Chef А432-83A: в названии и описании «от 3 лет»
UPDATE public.products SET min_age_months = 36
 WHERE id = '535dec67-b7de-4e3c-97ee-1134e1ae7a74' AND min_age_months = 24;

-- брелок-кейкап HZJJ-9: в названии и описании «от 6 лет»
UPDATE public.products SET min_age_months = 72
 WHERE id = '6636eb9c-80eb-47a1-9f3d-78fc71f0e0a3' AND min_age_months = 36;

-- «Ресторан» Smoneo: коробка «3+», в характеристике 3 года, в названии «от 1.5 лет»
UPDATE public.products SET name = 'Конструктор Smoneo Ресторан для малышей — 81 крупная деталь, аналог Duplo, от 3 лет'
 WHERE id = '3f36fb2d-a665-4772-805d-f6fd59500e06'
   AND name = 'Конструктор Smoneo Ресторан для малышей — 81 крупная деталь, аналог Duplo, от 1.5 лет';

-- Автотрек-пазл 1102AD: коробка «3+», в характеристике 3 года, в описании «от года»
UPDATE public.products
   SET description = replace(replace(description,
         'Подходит для детей от года', 'Подходит для детей от 3 лет'),
         'для малышей от года', 'для детей от 3 лет')
 WHERE id = 'eac5af25-4452-46a0-b2e4-9ab1f61c0928'
   AND strpos(description, 'Подходит для детей от года') > 0
   AND strpos(description, 'для малышей от года') > 0;

COMMIT;

-- ── 2. ПРОВЕРИТЬ ──────────────────────────────────────────────────────────
--  Ожидаемо: восемь строк; у шести «let» — 3 или 6 (брелок), ответ о
--  возрасте — «от 3…» / «от 6…»; у «Ресторана» в названии «от 3 лет»; у
--  автотрека «ot_goda» = false.

SELECT left(p.name, 60) AS tovar, p.min_age_months / 12 AS let,
       (strpos(p.description, 'от года') > 0) AS ot_goda,
       (SELECT left(q.answer_text, 60) FROM public.product_questions q
         WHERE q.product_id = p.id AND q.is_auto_generated AND q.question_text LIKE 'С какого возраста%' LIMIT 1) AS otvet_o_vozraste
  FROM public.products p
 WHERE p.id IN ('acc9cc75-53bf-4b86-a0cd-b515dccc4e93', 'dfede753-18e1-4e68-884b-b5766683f76c', '80e16267-bd63-486b-a852-67ce7b694e60', '56be98a6-d59d-4e02-9db6-0141831ce95a', '535dec67-b7de-4e3c-97ee-1134e1ae7a74', '6636eb9c-80eb-47a1-9f3d-78fc71f0e0a3',
                '3f36fb2d-a665-4772-805d-f6fd59500e06', 'eac5af25-4452-46a0-b2e4-9ab1f61c0928')
 ORDER BY 1;
