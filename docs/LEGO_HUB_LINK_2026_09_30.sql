-- =====================================================================================
-- «Конструкторы мальчикам»: ссылка на наборы LEGO — на /brand/lego
-- =====================================================================================
-- 30 сентября 2026. Решение владельца: главная страница LEGO — /brand/lego
-- («будут страницы в будущем бренд LEGO для девочек и малышей»). Связка
-- «Конструкторы мальчикам + LEGO» с теми же 14 наборами закрыта `noindex`
-- (код: BRAND_HUBS в constants/index.ts). В тексте раздела на неё стояла
-- ссылка — теперь она ведёт на главную страницу LEGO.
--
-- Меняется одна фраза, остальной текст — те же байты. Пишет, только если
-- текст такой же, как 30 сентября (md5); иначе UPDATE 0 и ничего не меняется.
--
-- Проверено запросом на чтение к бою: замена находит фразу ровно один раз,
-- старого адреса в тексте не остаётся, md5 после — b5fc2fe7….
--
-- Как применить: SQL-редактор Supabase, файл целиком. Ожидается UPDATE 1.
-- =====================================================================================

UPDATE public.categories
SET seo_text = replace(
  seo_text,
  'а все наборы LEGO этого раздела собраны на одной странице — <a href="/catalog/constructors-root/konstruktory-malchikam/brand/lego">конструкторы LEGO для мальчиков</a>',
  'а все наборы LEGO собраны на одной странице — <a href="/brand/lego">конструкторы LEGO</a>'
)
WHERE id = '2df67fed-6f86-4121-bb4d-bae3d049cd38'
  AND md5(seo_text) = 'a6688bc6491709a9ba61d031922259c8';

-- Проверка: должно вернуть new_link = true, old_link = false
SELECT slug,
       position('href="/brand/lego"' in seo_text) > 0 AS new_link,
       position('konstruktory-malchikam/brand/lego' in seo_text) > 0 AS old_link,
       md5(seo_text) = 'b5fc2fe7758dc5d0f9faf856bd630e90' AS as_expected
FROM public.categories
WHERE id = '2df67fed-6f86-4121-bb4d-bae3d049cd38';
