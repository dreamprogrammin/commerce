-- ── 0. ПОСМОТРЕТЬ, ЧТО СЕЙЧАС ─────────────────────────────────────────────

SELECT slug, seo_description
  FROM public.brands
 WHERE slug = 'lego';


-- ── 1. ВЕРНУТЬ СЛОВО ──────────────────────────────────────────────────────
--  Ожидаемо: UPDATE 1.

BEGIN;

UPDATE public.brands
   SET seo_description = 'Оригинальные конструкторы LEGO City, Marvel, DC и One Piece для детей от 4 лет — с доставкой по Алматы за 1–3 рабочих дня и по Казахстану за 3–7.'
 WHERE slug = 'lego'
   AND seo_description = 'Оригинальные наборы LEGO City, Marvel, DC и One Piece для детей от 4 лет — с доставкой по Алматы за 1–3 рабочих дня и по Казахстану за 3–7.';

COMMIT;


-- ── 2. ПРОВЕРИТЬ ──────────────────────────────────────────────────────────
--  Ожидаемо: одна строка, est_konstruktor > 0.

SELECT slug,
       position('онструктор' IN seo_description) AS est_konstruktor,
       seo_description
  FROM public.brands
 WHERE slug = 'lego';

