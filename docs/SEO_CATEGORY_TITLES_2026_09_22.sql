-- ── 0. ПОСМОТРЕТЬ ─────────────────────────────────────────────────────────

SELECT slug, seo_h1, seo_title
  FROM public.categories
 WHERE slug IN ('kukly-lol', 'tolokar')
 ORDER BY slug;

-- ── 1. ПОМЕНЯТЬ ───────────────────────────────────────────────────────────
--  Ожидаемо: UPDATE 1 и UPDATE 1.

BEGIN;

UPDATE public.categories
   SET seo_h1    = 'Куклы ЛОЛ (L.O.L. Surprise) для девочек',
       seo_title = 'Куклы ЛОЛ (L.O.L. Surprise) — купить в Алматы | Ухтышка'
 WHERE slug = 'kukly-lol'
   AND seo_h1 = 'Куклы L.O.L для девочек'
   AND seo_title = 'Куклы L.O.L для девочек — купить в Казахстане | Ухтышка';

UPDATE public.categories
   SET seo_h1    = 'Толокары для детей',
       seo_title = 'Толокар для детей — машинки-толокары в Алматы | Ухтышка'
 WHERE slug = 'tolokar'
   AND seo_h1 = 'Толокары для малышей'
   AND seo_title = 'Толокары для детей — купить в Казахстане | Ухтышка';

COMMIT;

-- ── 2. ПРОВЕРИТЬ ──────────────────────────────────────────────────────────

