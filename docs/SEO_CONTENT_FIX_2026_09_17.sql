-- Правки текстов карточек товара. Запускает владелец в SQL-редакторе Supabase.
--
-- Найдено сверкой всех 178 карточек прод-базы 17 сентября 2026. Здесь только
-- то, что нельзя починить кодом: это содержимое строк, а не шаблон.
--
-- Все правки — семь описаний. Шесть из них называют не тот товар, у которого
-- стоят: скопировали текст соседней модели и не поменяли артикул или цвет.
-- Человек, пришедший из поиска по артикулу, видит в сниппете чужой номер.
--
-- Каждый UPDATE сверяет и id, и прежний текст. Если текст уже поправили руками,
-- строка не тронется и в отчёте будет 0 — это нормально, а не ошибка.
--
-- Перед запуском ничего снимать не нужно: правки точечные и обратимые,
-- прежние значения приведены в комментариях над каждой.
-- ═══════════════════════════════════════════════════════════════════════════

BEGIN;

-- ── 1. Артикул в описании не тот, что в названии ────────────────────────────

-- Было: «Smoneo Playing Train 77013» при названии 77008.
-- 77013 — это другой набор; в базе его нет вовсе.
UPDATE public.products
SET seo_description = 'Конструктор Smoneo Playing Train 77008 — поезд-трансформер, 92 деталей, аналог Duplo, для детей 3–6 лет. Купить в Ухтышка с доставкой по Казахстану.'
WHERE id = 'ba8757e0-db8d-429f-8210-815188c086e9'
  AND seo_description LIKE '%77013%';

-- Было: «MOKA M1A2 2033S» при названии M1A2K 2033.
-- Рядом в каталоге есть «MOKA M1A2 2033 зелёный камуфляж» — описание, судя по
-- всему, взято у него, а «S» дописана вручную.
UPDATE public.products
SET seo_description = 'Радиоуправляемый танк MOKA M1A2K 2033 песочный камуфляж — поворот башни 360°, гусеницы, режим VS, 2.4 GHz. Купить в Ухтышка с доставкой по Казахстану.'
WHERE id = '00c3e8b4-9ebd-4c60-ba24-c764b97fea1e'
  AND seo_description LIKE '%M1A2 2033S%';

-- Было: «Капибара KS105» при названии KS105G.
-- В каталоге три Капибары — KS105G зелёная, KS105K коричневая, KS105R розовая,
-- и буква в артикуле — единственное, чем они различаются.
UPDATE public.products
SET seo_description = 'Каталка-твистер Капибара KS105G зелёная — ковш-погрузчик, светящиеся колёса. Купить в Ухтышка с доставкой по Казахстану.'
WHERE id = '4dd5375a-3686-4841-9daa-d313d80cda3c'
  AND seo_description LIKE '%KS105 зелёная%';

-- ── 2. Описание от товара другого цвета ─────────────────────────────────────

-- Было слово в слово описание синего вертолёта на жёлтом. Два товара делили
-- один текст: поиск видел у них одинаковый сниппет про синий.
UPDATE public.products
SET seo_description = 'Летающий вертолёт AIRCRAFT JM9198/Y жёлтый — управление от руки, USB зарядка, безопасные крылышки. Купить в Ухтышка с доставкой по Казахстану.'
WHERE id = 'c7ef6de3-0f7c-41e0-84b9-e22ee9224eb0'
  AND seo_description LIKE '%JM9198/B синий%';

-- Было «HW31 серый» на синем самолёте — тот же случай, что с вертолётом.
UPDATE public.products
SET seo_description = 'Радиоуправляемый самолёт HW31/B синий — EPP пена, гироскоп, дальность 300 м, LED огни для ночных полётов. Купить в Ухтышка с доставкой по Казахстану.'
WHERE id = '39926ad8-77c1-47c1-bf75-18cb79bce9cc'
  AND seo_description LIKE '%HW31 серый%';

-- ── 3. Предложения слиплись без точки ───────────────────────────────────────

-- Было: «…для праздников и прогулок Купить в Ухтышка … по Казахстану Хит …».
UPDATE public.products
SET seo_description = 'Пистолет мыльных пузырей 2188-78 с подсветкой — яркое световое шоу, для праздников и прогулок. Купить в Ухтышка с доставкой по Казахстану. Хит праздников!'
WHERE id = 'a6079d6d-7a8f-4ac3-8980-4d001797deb3'
  AND seo_description LIKE '%прогулок Купить%';

-- Было: «…безопасный пластик Купить в Ухтышка…».
UPDATE public.products
SET seo_description = 'Игровой набор Кухня Tourist 008-601A чемодан 3в1 — плита и аксессуары, безопасный пластик. Купить в Ухтышка с доставкой по Казахстану. Отличный подарок!'
WHERE id = '3b636cf1-ac7b-4c69-ae5a-1520ad9c2fcc'
  AND seo_description LIKE '%пластик Купить%';

-- ── Проверка: ни в одном описании не осталось чужого артикула или цвета ─────
SELECT
  count(*) FILTER (WHERE seo_description LIKE '%77013%')          AS smoneo_77013,
  count(*) FILTER (WHERE seo_description LIKE '%M1A2 2033S%')     AS moka_2033s,
  count(*) FILTER (WHERE seo_description LIKE '%KS105 зелёная%')  AS kapibara_bez_bukvy,
  count(*) FILTER (WHERE seo_description LIKE '%JM9198/B синий%'
                     AND name LIKE '%JM9198/Y%')                  AS vertolyot_chuzhoy_cvet,
  count(*) FILTER (WHERE seo_description LIKE '%HW31 серый%'
                     AND name LIKE '%HW31/B%')                    AS samolyot_chuzhoy_cvet,
  count(*) FILTER (WHERE seo_description ~ '[а-яё] Купить')       AS bez_tochki
FROM public.products;
-- Ожидается шесть нулей.

COMMIT;
