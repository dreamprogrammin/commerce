--  ПРОВЕРЕНО ЗАПУСКОМ на локальной базе в транзакции с откатом, три случая:
--  запись как на бою (с «?»), пустая таблица и повторный запуск.

-- ── 0. ПОСМОТРЕТЬ, ЧТО ЕСТЬ ───────────────────────────────────────────────
--  На бою 22 сентября: одна активная запись, в адресе «?».

SELECT name, address, working_hours, is_active
  FROM public.pickup_points
 ORDER BY is_active DESC, display_order;


-- ── 1. ПОПРАВИТЬ ИЛИ ЗАВЕСТИ ПУНКТ ────────────────────────────────────────

BEGIN;

DO $$
DECLARE
  n integer;
BEGIN
  SELECT count(*) INTO n FROM public.pickup_points WHERE is_active;

  IF n > 1 THEN
    RAISE EXCEPTION 'активных пунктов %, ожидался один или ни одного. Ничего не изменено.', n;
  ELSIF n = 1 THEN
    UPDATE public.pickup_points
       SET address = 'г. Алматы, мкр. Шапагат, ул. Амангельды, 100',
           working_hours = 'ежедневно с 9:00 до 22:00',
           phone = '+7 702 537 94 73',
           updated_at = now()
     WHERE is_active;
  ELSE
    INSERT INTO public.pickup_points (name, address, working_hours, phone, note, is_active, display_order)
    VALUES (
      'Склад Ухтышки',
      'г. Алматы, мкр. Шапагат, ул. Амангельды, 100',
      'ежедневно с 9:00 до 22:00',
      '+7 702 537 94 73',
      NULL,   -- сюда пригодится «вход со двора», «второй этаж» и прочее, если есть
      TRUE,
      0
    );
  END IF;
END $$;

COMMIT;


-- ── 2. ПРОВЕРИТЬ ──────────────────────────────────────────────────────────
--  Ожидаемо: одна строка, est_nomer_doma и est_22 больше нуля, voprosa = false.

SELECT name,
       address,
       working_hours,
       phone,
       position('100' IN address)          AS est_nomer_doma,   -- должно быть > 0
       position('22:00' IN working_hours)  AS est_22,           -- должно быть > 0
       address LIKE '%?%'                  AS voprosa           -- должно быть false
  FROM public.pickup_points
 WHERE is_active
 ORDER BY display_order;
