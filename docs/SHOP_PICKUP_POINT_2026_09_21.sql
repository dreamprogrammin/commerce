-- ── 0. СНАЧАЛА ПОСМОТРЕТЬ, ЧТО ЕСТЬ ───────────────────────────────────────
--  Ожидаемо: ноль строк.

SELECT count(*) AS vsego, count(*) FILTER (WHERE is_active) AS aktivnyh
  FROM public.pickup_points;


-- ── 1. ЗАВЕСТИ ПУНКТ ──────────────────────────────────────────────────────
--  Ожидаемо: INSERT 0 1. Если раздел 0 показал активную запись — не
--  запускайте, а поправьте существующую (раздел 3).

BEGIN;

INSERT INTO public.pickup_points (name, address, working_hours, phone, note, is_active, display_order)
SELECT
  'Склад Ухтышки',
  'г. Алматы, мкр. Шапагат, ул. Амангельды, 100',
  'ежедневно с 9:00 до 22:00',
  '+7 702 537 94 73',
  NULL,   -- сюда пригодится «вход со двора», «второй этаж» и прочее, если есть
  TRUE,
  0
WHERE NOT EXISTS (SELECT 1 FROM public.pickup_points WHERE is_active);

COMMIT;


-- ── 2. ПРОВЕРИТЬ ──────────────────────────────────────────────────────────
--  Ожидаемо: одна строка, в адресе есть «100», в часах — «22:00».

SELECT name,
       address,
       working_hours,
       phone,
       position('100' IN address)     AS est_nomer_doma,   -- должно быть > 0
       position('22:00' IN working_hours) AS est_22        -- должно быть > 0
  FROM public.pickup_points
 WHERE is_active
 ORDER BY display_order;


