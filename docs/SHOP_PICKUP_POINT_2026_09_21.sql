--  Теперь скрипт сам смотрит, что есть: одна активная запись — правит её,
--  ни одной — заводит новую, больше одной — откатывается, ничего не меняя.
--
--  ОТКУДА ЗНАЧЕНИЯ. Номер дома (100) и часы (с 9:00 до 22:00) назвал владелец
--  21 сентября 2026. Телефон — тот, что стоит в разметке сайта и на `/about`.
