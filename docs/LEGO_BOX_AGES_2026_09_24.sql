--  ЗАЧЕМ. Сверил возраст всех 14 наборов LEGO с фотографиями их коробок
--  (первое фото карточки). У десяти совпадает, у четырёх — нет:
--
--    60355 «Водная полиция»           на коробке 6+   в карточке 4+
--    60401 «Паровой каток»             на коробке 5+   в карточке 4+
--    60411                             на коробке 5+   в карточке 4+
--    76290 «Мстители против Левиафана» на коробке 7+   в карточке не указан
--
--  А у 60411 и название от другого набора: «Полицейский участок и вертолёт
--  3 этажа камеры транспорт 5-6 минифигурок». На фото, в описании карточки и
--  по числу деталей (85) это пожарно-спасательный вертолёт с водомётами и
--  пилотом, от 5 лет. Адрес карточки не меняется — только название.
--
--  Эти возрасты попали и в текст «Конструкторов мальчикам» (SEO_LEGO_RC от
--  23 сентября): «наборы с пометкой 4+… до водной полиции на 278» — неверно.
--  Две строки текста исправляются здесь же.
--
--  Автоответы «С какого возраста…» в вопросах карточек подтянет триггер
--  (миграция 20260923120000). Пишет, только если значения такие же, как
--  24 сентября. Повторный запуск ничего не меняет.
--  ПРОВЕРЕНО ЗАПУСКОМ на локальной базе с копией боевых значений, с откатом.

-- ── 1. ПОМЕНЯТЬ ───────────────────────────────────────────────────────────
--  Ожидаемо: UPDATE 1 пять раз.

BEGIN;

UPDATE public.products SET min_age_months = 72
 WHERE id = '6caf9879-de7d-4a6b-9a05-a05365d4748e' AND min_age_months = 48;

UPDATE public.products SET min_age_months = 60
 WHERE id = 'cc8c7343-45c8-484a-b571-f102f4910aab' AND min_age_months = 48;

UPDATE public.products
   SET min_age_months = 60,
       name = 'Конструктор LEGO City 60411 Пожарно-спасательный вертолёт с водомётами и пилотом'
 WHERE id = '1d30a829-7a1d-457e-97ce-e71e76a74ca4'
   AND min_age_months = 48
   AND name = 'Конструктор LEGO City 60411 Полицейский участок и вертолёт 3 этажа камеры транспорт 5-6 минифигурок';

UPDATE public.products SET min_age_months = 84
 WHERE id = '0fefda9a-e8e7-441c-b103-5b8a144f5556' AND min_age_months IS NULL;

UPDATE public.categories
   SET seo_text = replace(replace(seo_text,
         '4–5 лет — наборы LEGO City и Marvel с пометкой 4+: от пожарного мотоцикла на 57 деталей до водной полиции на 278.',
         '4–5 лет — первые наборы LEGO на 57–85 деталей: пожарный мотоцикл и Железный человек против Халка с пометкой 4+, паровой каток и пожарный вертолёт — 5+.'),
         '6–7 лет — наборы на 140–423 детали: погоня LEGO City, межзвёздный корабль, меха-броня Бэтмена, машины CaDA и Sluban с пультом.',
         '6–7 лет — наборы на 140–423 детали: водная полиция и погоня LEGO City, межзвёздный корабль, меха-броня Бэтмена, машины CaDA и Sluban с пультом; Мстители против Левиафана — с 7 лет.')
 WHERE slug = 'konstruktory-malchikam'
   AND strpos(seo_text, '4–5 лет — наборы LEGO City и Marvel с пометкой 4+: от пожарного мотоцикла на 57 деталей до водной полиции на 278.') > 0
   AND strpos(seo_text, '6–7 лет — наборы на 140–423 детали: погоня LEGO City, межзвёздный корабль, меха-броня Бэтмена, машины CaDA и Sluban с пультом.') > 0;

COMMIT;

-- ── 2. ПРОВЕРИТЬ ──────────────────────────────────────────────────────────
--  Ожидаемо: 60355 — 6 лет, 60401 и 60411 — 5 лет, 76290 — 7 лет; у 60411
--  новое название; ответы «С какого возраста…» — «от 6…», «от 5…»; в тексте
--  «Конструкторов мальчикам» новые строки есть, старых нет.

SELECT substring(p.name from '\d{5}') AS nabor, p.min_age_months / 12 AS let, left(p.name, 80) AS nazvanie,
       (SELECT left(q.answer_text, 70) FROM public.product_questions q
         WHERE q.product_id = p.id AND q.is_auto_generated AND q.question_text LIKE 'С какого возраста%' LIMIT 1) AS otvet_o_vozraste
  FROM public.products p
 WHERE p.id IN ('6caf9879-de7d-4a6b-9a05-a05365d4748e', 'cc8c7343-45c8-484a-b571-f102f4910aab',
                '1d30a829-7a1d-457e-97ce-e71e76a74ca4', '0fefda9a-e8e7-441c-b103-5b8a144f5556')
 ORDER BY 1;

SELECT strpos(seo_text, 'первые наборы LEGO на 57–85 деталей') > 0 AS novaya_stroka,
       strpos(seo_text, 'до водной полиции на 278') = 0 AS staroi_net
  FROM public.categories WHERE slug = 'konstruktory-malchikam';
