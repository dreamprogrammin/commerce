       (SELECT count(*) FROM public.products p WHERE p.category_id = c.id AND p.is_active) AS tovarov,
       CASE c.slug
         WHEN 'katalki' THEN c.seo_text LIKE '%Как выбрать каталку%' AND c.seo_text LIKE '%/catalog/kiddy/tolokar%'
