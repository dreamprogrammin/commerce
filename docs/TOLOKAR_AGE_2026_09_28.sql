-- ═══════════════════════════════════════════════════════════════════════════
--  «Толокары»: все семь моделей — с 1 года — 28.09.2026
-- ═══════════════════════════════════════════════════════════════════════════
--
--  ЗАЧЕМ. Решение владельца 28 сентября: «все 7 — с 1 года». С этого дня
--  раздел «Толокары» показывает возраст своих моделей абзацем с цифрами, и
--  рядом с советом «примерно с года» стояло: толокары Sport 5566 — «от 2
--  лет», каталки-твистеры Bibi Car KS105 — «от 3 лет».
--
--  ⚠️ БЛОК 2 РАЗВОРАЧИВАЕТ ПРАВКУ 23 СЕНТЯБРЯ. Тогда твистерам KS105 возраст
--  подняли с 1 года до 3 лет (`docs/PRODUCT_CARDS_FIX_2026_09_22.sql`, его
--  запускал владелец): в их описании дважды сказано «рекомендована детям
--  старше 3 лет». Блок 2 меняет и возраст, и обе эти фразы. Запускайте его,
--  только если на коробке KS105 написано «от 1 года» (или 12 месяцев). Если
--  на коробке 3+ — блок 2 не запускайте: сайт от имени производителя
--  пообещает то, чего производитель не обещает.
--
--  ЧТО ДЕЛАЕТ.
--   Блок 1. Толокары Sport 5566 (Y, B, R, BR): min_age_months 24 → 12.
--   Блок 2. Твистеры Bibi Car KS105 (G, K, R): min_age_months 36 → 12; в
--           описании «Рекомендована детям старше 3 лет.» и пункт списка
--           «Рекомендована детям от 3 лет» → «… от 1 года».
--   Годы (min_age_years) пересчитает триггер trigger_sync_product_age, ответ
--   на автоматический вопрос «С какого возраста можно играть с этой
--   игрушкой?» перепишет trigger_sync_product_age_question: «Производитель
--   рекомендует для детей от 1 года.» Каждое UPDATE — только там, где
--   значение ещё прежнее: правку руками не затрёт, повторный запуск ничего
--   не меняет (UPDATE 0).
--
--  Абзац с цифрами раздела, карточки, фильтр по возрасту, фид Merchant Center
--  и llms.txt возьмут новый возраст сами — кода под это не нужно.
--
--  ПРОВЕРЕНО ЗАПУСКОМ на локальной базе, в транзакции с откатом: семи
--  товарам выставлены боевые значения (KS105 — 36 месяцев, обе фразы «3 лет»
--  в описании) и автоматические вопросы о возрасте с боевыми ответами («…для
--  детей от 3 лет.», «Производитель рекомендует от 2 лет.»). Первый прогон —
--  UPDATE 4, UPDATE 3, UPDATE 3: у всех семи 12 месяцев и 1 год, «3 лет» в
--  описаниях нет, ответ — «Производитель рекомендует для детей от 1 года.».
--  Повторный прогон — UPDATE 0, UPDATE 0, UPDATE 0.

-- ── 0. ПОСМОТРЕТЬ ─────────────────────────────────────────────────────────
--  Ожидаемо: семь строк. У Sport 5566 — 24 месяца, у KS105 — 36 и обе фразы
--  «3 лет» в описании.

SELECT sku, min_age_months, min_age_years,
       description LIKE '%Рекомендована детям старше 3 лет.%' AS fraza_starshe_3,
       description LIKE '%Рекомендована детям от 3 лет<%'    AS fraza_ot_3
  FROM public.products
 WHERE id IN ('096e5f13-7f8f-4ce6-82c4-a3827b55ebe5', '15ff30d5-d5a8-4692-8f2a-4dba7f082e96',
              'a01732e6-802f-402a-a11d-e7220d5763ed', 'ad702ae2-1cef-4507-b28a-fdb15b084ccc',
              '4dd5375a-3686-4841-9daa-d313d80cda3c', 'e8f8393c-0f51-41be-b233-4517cdd1e072',
              'b9ea8841-041a-427a-9d0b-0b6820800d05')
 ORDER BY sku;

-- ── 1. ТОЛОКАРЫ SPORT 5566 — С 1 ГОДА ────────────────────────────────────
--  Ожидаемо: UPDATE 4.

BEGIN;

UPDATE public.products
   SET min_age_months = 12
 WHERE id IN ('096e5f13-7f8f-4ce6-82c4-a3827b55ebe5',   -- 5566Y
              '15ff30d5-d5a8-4692-8f2a-4dba7f082e96',   -- 5566B
              'a01732e6-802f-402a-a11d-e7220d5763ed',   -- 5566R
              'ad702ae2-1cef-4507-b28a-fdb15b084ccc')   -- 5566BR
   AND min_age_months = 24;

COMMIT;

-- ── 2. ТВИСТЕРЫ BIBI CAR KS105 — С 1 ГОДА ────────────────────────────────
--  ⚠️ Только если на коробке KS105 «от 1 года» — см. шапку.
--  Ожидаемо: UPDATE 3, затем UPDATE 3.

BEGIN;

UPDATE public.products
   SET min_age_months = 12
 WHERE id IN ('4dd5375a-3686-4841-9daa-d313d80cda3c',   -- KS105G
              'e8f8393c-0f51-41be-b233-4517cdd1e072',   -- KS105K
              'b9ea8841-041a-427a-9d0b-0b6820800d05')   -- KS105R
   AND min_age_months = 36;

UPDATE public.products
   SET description = replace(replace(description,
         'Рекомендована детям старше 3 лет.', 'Рекомендована детям от 1 года.'),
         'Рекомендована детям от 3 лет<', 'Рекомендована детям от 1 года<')
 WHERE id IN ('4dd5375a-3686-4841-9daa-d313d80cda3c',
              'e8f8393c-0f51-41be-b233-4517cdd1e072',
              'b9ea8841-041a-427a-9d0b-0b6820800d05')
   AND description LIKE '%Рекомендована детям старше 3 лет.%'
   AND description LIKE '%Рекомендована детям от 3 лет<%';

COMMIT;

-- ── 3. ПРОВЕРИТЬ ──────────────────────────────────────────────────────────
--  Ожидаемо: у всех семи min_age_months = 12 и min_age_years = 1, «3 лет» в
--  описании нет, ответ о возрасте — «Производитель рекомендует для детей от
--  1 года.» (пусто — у товара нет такого вопроса). Если блок 2 не запускали,
--  у KS105 останутся 36, 3, «3 лет» и «от 3 лет».

SELECT p.sku, p.min_age_months, p.min_age_years,
       p.description LIKE '%3 лет%' AS v_opisanii_3_let,
       q.answer_text AS otvet_o_vozraste
  FROM public.products p
  LEFT JOIN public.product_questions q
    ON q.product_id = p.id
   AND q.is_auto_generated
   AND q.question_text = 'С какого возраста можно играть с этой игрушкой?'
 WHERE p.id IN ('096e5f13-7f8f-4ce6-82c4-a3827b55ebe5', '15ff30d5-d5a8-4692-8f2a-4dba7f082e96',
                'a01732e6-802f-402a-a11d-e7220d5763ed', 'ad702ae2-1cef-4507-b28a-fdb15b084ccc',
                '4dd5375a-3686-4841-9daa-d313d80cda3c', 'e8f8393c-0f51-41be-b233-4517cdd1e072',
                'b9ea8841-041a-427a-9d0b-0b6820800d05')
 ORDER BY p.sku;
