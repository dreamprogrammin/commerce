--
--  ЧТО ЭТО. Готовый запрос к БОЕВОЙ базе. Сам не применяется: раздел 0
--  считает, раздел 1 правит, раздел 2 проверяет. Схему не меняет — только
--  тексты, поэтому место файла не в миграциях.
--
--  ПОЧЕМУ ЗАДАЧА ИЗМЕНИЛАСЬ. В HANDOFF значилось «83 карточки с ДОСЛОВНО
--  одинаковым абзацем „Доставляем по всему Казахстану — в Алматы, Астану,
--  Шымкент…“». Выборка по бою 21 сентября: такого абзаца в базе НЕТ ВОВСЕ
--  (0 вхождений) — его убрал запуск `SEO_CONTENT_FIX_2026_09_16.sql`.
--
--  Осталось другое: 66 карточек из 178 несут ПАРУ
--
--      <h2>Купить <название> в Казахстане — Ухтышка</h2>
--      <p>Заказывайте <товар> в магазине Ухтышка — доставляем по всему
--         Казахстану: в Алматы, Астану, Шымкент и другие города…</p>
--
--  Дословных дублей среди них всего 4 карточки (в тексте стоит название
--  товара), так что как «дубль для поиска» это уже почти не беда. Убирается
--  по другой причине: абзац ничего не сообщает о товаре, а условия доставки
--  и так есть в разметке и на `/terms`.
--
--  ЦИФРЫ СПРОСА (Search Console, sc-domain:uhti.kz, 90 дней, `gsc-queries.mjs`):
--  все запросы со словами «алматы / астан / шымкент / казахстан / доставк» —
--  43 запроса, 235 показов, **0 кликов**. Названия городов остаются на
--  страницах разделов, брендов и в `/terms`, так что сайт их не теряет.
--
--  УБИРАЕТСЯ ПАРА ЦЕЛИКОМ, А НЕ ОДИН АБЗАЦ. Во всех 66 карточках под этим
--  заголовком лежит ровно один абзац, а сразу за ним начинается следующий
--  заголовок (`<h3>Почему…`). Удали только абзац — останется заголовок
--  «Купить … в Казахстане — Ухтышка» без единой строки под ним.
--
--  ПРОВЕРЕНО ЗАПУСКОМ, а не глазами: три настоящих описания с боя положены
--  во временную таблицу локальной базы, запрос применён, результат осмотрен,
--  `ROLLBACK`. После правки в описании не осталось ни «Купить», ни «по всему
--  Казахстану», HTML целый — абзац с фактами о товаре сразу переходит в
--  следующий заголовок.
--
--  ИДЕМПОТЕНТНО: второй прогон задевает ноль строк.
--
--  КАК ЗАПУСКАТЬ: разделами, в транзакции, сверяя число задетых строк.

-- ── 0. СНАЧАЛА ПОСЧИТАТЬ ───────────────────────────────────────────────────
--  Ожидаемо на 21 сентября: 66 активных карточек. Снятые с продажи анонимным
--  ключом не видны, поэтому итог может быть чуть больше — это нормально,
--  чистить их тоже надо.

SELECT count(*) AS kartochek_s_abzacem,
       count(*) FILTER (WHERE is_active) AS iz_nih_aktivnyh
  FROM public.products
 WHERE description ~ '<h2[^>]*>[^<]*Купить[^<]*</h2>\s*<p>[^<]*достав(им|ляем) по всему Казахстану[^<]*</p>';


-- ── 1. УБРАТЬ ЗАГОЛОВОК ВМЕСТЕ С АБЗАЦЕМ ──────────────────────────────────
--  Ожидаемо: столько строк, сколько показал раздел 0.

BEGIN;

UPDATE public.products
   SET description = trim(regexp_replace(
         description,
         '<h2[^>]*>[^<]*Купить[^<]*</h2>\s*<p>[^<]*достав(им|ляем) по всему Казахстану[^<]*</p>\s*',
         '',
         'g'))
 WHERE description ~ '<h2[^>]*>[^<]*Купить[^<]*</h2>\s*<p>[^<]*достав(им|ляем) по всему Казахстану[^<]*</p>';

--  Посмотреть «UPDATE N» и сверить с разделом 0. Не сошлось — ROLLBACK.
COMMIT;


-- ── 2. ПРОВЕРИТЬ РЕЗУЛЬТАТ ────────────────────────────────────────────────
--  Ожидаемо: все три числа — ноль.

SELECT count(*) FILTER (WHERE description LIKE '%по всему Казахстану%')     AS ostalos_abzacev,
       count(*) FILTER (WHERE description LIKE '%в Казахстане — Ухтышка%')  AS ostalos_zagolovkov,
       count(*) FILTER (WHERE description ~ '<h2[^>]*>[^<]*</h2>')          AS pustyh_zagolovkov
  FROM public.products;
