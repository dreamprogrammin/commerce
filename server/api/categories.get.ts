import { PUBLIC_CATEGORY_COLUMNS } from '~/constants/categoryColumns'

/**
 * Список категорий с серверным кешем.
 *
 * Зачем. Выборка всех категорий делается на КАЖДЫЙ рендер: её зовут главная,
 * `/catalog`, страница категории, карточка товара, мега-меню и мобильная
 * панель. Замер на боевой базе: 97 КБ и 1.5 с на запрос, причём вес тут не
 * главное — один круг до Supabase стоит 400–650 мс сам по себе. Категорий 64,
 * и меняются они раз в месяц: платить секундой за каждый рендер незачем.
 *
 * Почему кеш здесь, а не в правилах маршрутов. ISR на `/catalog/**` уже
 * пробовался и откачен (см. комментарий в `nuxt.config.ts`): vercel-пресет
 * подменяет query-строку, и бренд-лендинги с фильтрами начинают отдавать
 * общую страницу категории. Кеш под данными такого побочного эффекта не
 * имеет: страница по-прежнему рендерится на каждый запрос со своими
 * параметрами, просто не ходит за одним и тем же списком.
 *
 * Обращение к PostgREST напрямую, а не через `serverSupabaseClient`,
 * намеренно: клиент из `@nuxtjs/supabase` привязан к запросу (куки, сессия),
 * а кеш общий на всех. Здесь нужен именно анонимный доступ — категории
 * публичны, RLS отдаёт их всем одинаково.
 *
 * `maxAge` 600 с при `staleMaxAge` 3600: правка категории в админке доедет
 * до витрины за десять минут, а если Supabase в этот момент недоступна,
 * посетитель получит вчерашний список вместо ошибки.
 */
export default defineCachedEventHandler(
  async () => {
    const { supabase } = useRuntimeConfig().public as {
      supabase: { url: string, key: string }
    }

    return await $fetch<unknown[]>(`${supabase.url}/rest/v1/categories`, {
      query: {
        select: PUBLIC_CATEGORY_COLUMNS,
        order: 'display_order',
      },
      headers: {
        apikey: supabase.key,
        Authorization: `Bearer ${supabase.key}`,
      },
    })
  },
  {
    name: 'categories',
    // Ключ постоянный: запрос всегда один и тот же, параметров у него нет.
    getKey: () => 'public',
    maxAge: 600,
    staleMaxAge: 3600,
    swr: true,
  },
)
