/**
 * Сброс серверного кеша списка категорий.
 *
 * Зачем. `server/api/categories.get.ts` кеширует выборку на 10 минут (и до
 * часа отдаёт устаревшее, пока обновляет в фоне). Для самих данных это
 * безобидно, но не для картинок: при замене картинки категории загрузчик
 * УДАЛЯЕТ прежний файл, а кеш ещё держит его путь — и вместо картинки
 * приходит 400.
 *
 * Ровно это и случилось 23 августа: в базе лежал `…-c5c26324`, превью
 * отдавало `…-f0543465`, прод `…-c20a8b90` — три разных пути, два из них на
 * уже удалённые файлы.
 *
 * Поэтому админка зовёт этот обработчик после каждого изменения категорий.
 *
 * Проверки прав здесь нет намеренно: сброс ничего не раскрывает и не меняет —
 * следующий запрос перечитает из базы то же самое, что отдаёт публичный
 * `/api/categories`. Единственный риск — частые сбросы, и он не опаснее
 * обычного обхода витрины.
 */
/*
 * Ключ собирается Nitro так (nitropack/dist/runtime/internal/cache.mjs:29):
 *
 *   [base, group, name, key + '.json'].join(':')
 *
 * где `base` внутри хранилища `cache` уже отброшен, `group` для
 * `defineCachedEventHandler` — `nitro/handlers` (строка 162), `name` и `key`
 * взяты из его опций: `categories` и `public`.
 *
 * Угадывать тут нельзя: с первой попытки я написал `nitro:functions:…` — это
 * группа для `cachedFunction`, а не для обработчика. Ошибка тихая, сброс
 * возвращал `ok: true` и не делал ничего. Проверяется временем ответа:
 * из кеша `/api/categories` отвечает за 6 мс, из базы — за полторы секунды.
 */
const CACHE_KEY = 'nitro/handlers:categories:public.json'

export default defineEventHandler(async () => {
  const storage = useStorage('cache')
  const existed = await storage.hasItem(CACHE_KEY)
  await storage.removeItem(CACHE_KEY)
  // `existed` возвращается наружу намеренно: если однажды ключ снова
  // разойдётся с тем, что строит Nitro, это будет видно сразу.
  return { ok: true, existed }
})
